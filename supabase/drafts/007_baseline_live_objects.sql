SET lock_timeout = '3s';

CREATE TABLE IF NOT EXISTS public.audit_rate_limits (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip         text        NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.audit_rate_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.audit_rate_limits FROM anon, authenticated;

DO $$
BEGIN
  IF to_regclass('public.audit_rate_limits_id_seq') IS NOT NULL THEN
    REVOKE ALL ON SEQUENCE public.audit_rate_limits_id_seq FROM anon, authenticated;
  END IF;
END
$$;

-- The limiter counts rows per key since a time (rateLimit.ts).
-- ON THE LIVE DATABASE: skip the statement below and run this one on its own,
-- outside any transaction or multi-statement batch (a plain build blocks every
-- rate-limit insert until it finishes):
--   CREATE INDEX CONCURRENTLY IF NOT EXISTS audit_rate_limits_ip_created_at_idx
--     ON public.audit_rate_limits (ip, created_at);
-- If a concurrent build fails it leaves an INVALID index that IF NOT EXISTS then
-- skips: STEP 3 checks validity; if false, DROP INDEX CONCURRENTLY that index
-- (RJ's step: it is a DROP) and build again.
CREATE INDEX IF NOT EXISTS audit_rate_limits_ip_created_at_idx
  ON public.audit_rate_limits (ip, created_at);

